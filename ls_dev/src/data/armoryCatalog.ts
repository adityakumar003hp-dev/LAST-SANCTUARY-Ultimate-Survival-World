// Map lookup dictionary for fast O(1) access
export const ARMORY_ITEMS_MAP: Record<string, ArmoryCatalogItem> = ARMORY_CATALOG.reduce(
  (acc, item) => {
    acc[item.id] = item;
    return acc;
  },
  {} as Record<string, ArmoryCatalogItem>
);

// Helper to validate exactly 100 unique items
export function validateArmoryCatalog(): { isValid: boolean; count: number; duplicates: string[] } {
  const seen = new Set<string>();
  const duplicates: string[] = [];
  for (const item of ARMORY_CATALOG) {
    if (seen.has(item.id)) {
      duplicates.push(item.id);
    }
    seen.add(item.id);
  }
  return {
    isValid: seen.size === 100 && duplicates.length === 0,
    count: seen.size,
    duplicates,
  };
}
